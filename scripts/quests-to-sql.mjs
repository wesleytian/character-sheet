// Turns scripts/quests.json into one idempotent import. Ids are generated here
// rather than by the database so a child can point at its parent without a
// title lookup - two quests can legitimately share a title.
import { readFileSync, writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';

const USER = process.argv[2];
if (!USER) throw new Error('usage: node scripts/quests-to-sql.mjs <user_id>');

const d = JSON.parse(readFileSync('scripts/quests.json', 'utf8'));
const rows = [];
let order = 0;

const push = (item, kind, phase, track, parent, depth) => {
  const id = randomUUID();
  rows.push({
    id, title: item.t, kind, phase, track,
    status: item.s ?? null, note: item.n ?? '', parent, order: order++, depth,
  });
  for (const c of item.children ?? []) push(c, kind, phase, track, id, depth + 1);
};

for (const g of d.main) for (const i of g.items) push(i, 'main', g.phase, '', null, 0);
for (const g of d.side) for (const i of g.items) push(i, 'side', '', g.track, null, 0);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

// One tab-separated literal rather than 208 VALUES rows: the same data in a
// third of the characters, which matters when it has to travel as a query.
const byId = new Map(rows.map((r) => [r.id, r]));
const tsv = rows.map((r) => [
  r.order,
  r.parent ? byId.get(r.parent).order : '',
  r.kind, r.phase, r.track, r.status ?? '', r.note, r.title,
].join('\t')).join('\n');

const sql = `-- Generated by scripts/quests-to-sql.mjs. ${rows.length} quests.
begin;

-- One title contains the other AND they are close in length. Without the
-- length guard "Run a marathon" matches "Run a marathon under three hours",
-- and a status jumps to a quest that is emphatically not the same quest.
create or replace function pg_temp.similar_title(a text, b text) returns boolean as $$
  select a = b
     or (least(length(a), length(b)) > 10
         and (a like '%' || b || '%' or b like '%' || a || '%')
         and least(length(a), length(b))::numeric / greatest(length(a), length(b)) > 0.8);
$$ language sql immutable;

create temp table stage (
  id uuid, title text, kind text, phase text, track text,
  status text, note text, parent_id uuid, parent_order int, display_order int,
  completed_on date
) on commit drop;

insert into stage (display_order, parent_order, kind, phase, track, status, note, title)
select split_part(l, E'\t', 1)::int,
       nullif(split_part(l, E'\t', 2), '')::int,
       split_part(l, E'\t', 3),
       split_part(l, E'\t', 4),
       split_part(l, E'\t', 5),
       nullif(split_part(l, E'\t', 6), ''),
       split_part(l, E'\t', 7),
       split_part(l, E'\t', 8)
from unnest(string_to_array(${q(tsv)}, E'\n')) as l;

update stage set id = gen_random_uuid();
update stage s set parent_id = p.id from stage p where p.display_order = s.parent_order;

-- Carry over anything already recorded. Titles were reworded for consistency,
-- so match on letters only and accept one title containing the other.
create temp table old_q on commit drop as
select id, title, status, completed_on, note, pinned,
       regexp_replace(lower(title), '[^a-z0-9]', '', 'g') as norm
from cs_quests where user_id = ${q(USER)}::uuid;

update stage s set
  status = coalesce(s.status, o.status),
  completed_on = o.completed_on,
  note = case when s.note = '' then o.note else s.note end
from old_q o
where pg_temp.similar_title(regexp_replace(lower(s.title), '[^a-z0-9]', '', 'g'), o.norm);

-- Keep a quest that is on the character card pinned after the swap.
create temp table keep_pinned on commit drop as
select distinct s.id from stage s join old_q o
  on regexp_replace(lower(s.title), '[^a-z0-9]', '', 'g') = o.norm
where o.pinned;

-- Anything already finished that the new list does not mention is history, not
-- clutter: keep it rather than deleting a completed quest and its date.
create temp table orphans on commit drop as
select o.* from old_q o
where o.status = 'done'
  and not exists (
    select 1 from stage s
    where pg_temp.similar_title(regexp_replace(lower(s.title), '[^a-z0-9]', '', 'g'), o.norm)
  );

delete from cs_quests where user_id = ${q(USER)}::uuid and kind in ('main', 'side', 'bucket');

insert into cs_quests (id, user_id, title, kind, track, phase, status, completed_on,
                       progress_current, progress_total, note, display_order, is_public,
                       pinned, parent_id)
select s.id, ${q(USER)}::uuid, s.title, s.kind, s.track, s.phase,
       coalesce(s.status, 'locked'),
       s.completed_on,
       null, null, s.note, s.display_order, true,
       exists (select 1 from keep_pinned k where k.id = s.id),
       s.parent_id
from stage s;

insert into cs_quests (user_id, title, kind, track, phase, status, completed_on,
                       progress_current, progress_total, note, display_order, is_public,
                       pinned, parent_id)
select ${q(USER)}::uuid, o.title, 'side', 'Already done', '', 'done', o.completed_on,
       null, null, o.note, 900, true, o.pinned, null
from orphans o;

commit;
`;
writeFileSync('scripts/quests.sql', sql);
console.log(`${rows.length} quests -> scripts/quests.sql`);
