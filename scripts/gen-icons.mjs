// Pulls only the Game Icons we actually use out of react-icons into a local
// module. Importing from 'react-icons/gi' drags in all 4,040 of them - a 7 MB
// chunk in dev and 3 MB of the production bundle - for the ~180 we name.
// Re-run after adding an icon to gameIcons.ts:  node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('src/gameIcons.ts', 'utf8');
const block = src.slice(src.indexOf('import {'), src.indexOf("} from 'react-icons/gi'"));
const wanted = [...new Set(block.match(/Gi[A-Za-z0-9]+/g) ?? [])].sort();

const lib = readFileSync('node_modules/react-icons/gi/index.mjs', 'utf8');
const out = [];
const missing = [];
for (const name of wanted) {
  const re = new RegExp(`export function ${name} \\(props\\) \\{\\n  return GenIcon\\((.*?)\\)\\(props\\);\\n\\}`, 's');
  const m = lib.match(re);
  if (!m) { missing.push(name); continue; }
  out.push(`export const ${name}: IconType = (props) => GenIcon(${m[1]} as IconTree)(props);`);
}
if (missing.length) throw new Error(`not found in react-icons/gi: ${missing.join(', ')}`);

writeFileSync('src/gi.ts',
  `// GENERATED by scripts/gen-icons.mjs - do not edit.\n`
  + `// Only the Game Icons this app names, so the bundle carries ${out.length}, not 4,040.\n`
  + `import { GenIcon } from 'react-icons/lib';\n`
  + `import type { IconType, IconTree } from 'react-icons';\n\n`
  + out.join('\n') + '\n');
console.log(`wrote src/gi.ts with ${out.length} icons`);
